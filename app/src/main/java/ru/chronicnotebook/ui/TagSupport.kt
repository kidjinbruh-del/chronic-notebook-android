package ru.chronicnotebook.ui

/**
 * Цвета тегов и подсказки для первого запуска.
 *
 * Цвет выводится из имени, а не хранится как случайный: тогда один и тот же
 * тег после экспорта и импорта выглядит так же, а в файле не нужно тащить
 * отдельное поле с цветом.
 */
private val TAG_PALETTE = intArrayOf(
    0xFF3F51B5.toInt(), // синий
    0xFF00897B.toInt(), // бирюзовый
    0xFF6A1B9A.toInt(), // фиолетовый
    0xFFAD1457.toInt(), // малиновый
    0xFF2E7D32.toInt(), // зелёный
    0xFFE65100.toInt(), // оранжевый
    0xFF4527A0.toInt(), // глубокий синий
    0xFF00838F.toInt(), // циан
)

/** Устойчивый к регистру цвет из палитры. */
fun tagColor(name: String): Int {
    val h = name.trim().lowercase().hashCode()
    return TAG_PALETTE[Math.floorMod(h, TAG_PALETTE.size)]
}

